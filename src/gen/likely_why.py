"""Write likely_why.js (LIKELY_WHY) from why/why.json: the spoken reasoning of each ★ question, read aloud by Hear why.

why.json is a list of {"id", "t"}, one per question in LIKELY_STARS (likely.js); t is what the narrator says, with
numbers and units in words and no digit or symbol the voice cannot read (the walkthrough rules). A recorded clip,
audio/why-<id>.mp3, must be made from the t it plays; change a t and its clip has to be recorded again.

    python3 gen/likely_why.py
"""
import json, os, re, sys

SRC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BAD = re.compile(r'[()\[\]/\\%=<>+*^≥≤→±μ"“”&#{}|]')

def main():
    rows = json.load(open(os.path.join(SRC, 'why', 'why.json'), encoding='utf-8'))
    stars = set(re.findall(r'^\s*"([^"]+)"\s*:', open(os.path.join(SRC, 'likely.js'), encoding='utf-8').read().split('LIKELY_STARS', 1)[1], re.M))
    errs, out = [], {}
    for r in rows:
        i, t = r['id'], re.sub(r'\s+', ' ', r['t']).strip()
        if i in out: errs.append(f'{i}: two scripts')
        if stars and i not in stars: errs.append(f'{i}: not a ★ question in likely.js')
        if re.search(r'\d', t): errs.append(f'{i}: a digit in spoken text')
        if BAD.search(t): errs.append(f'{i}: symbol {BAD.search(t).group()!r} in spoken text')
        if not 45 <= len(t.split()) <= 200: errs.append(f'{i}: {len(t.split())} words (45 to 200)')
        out[i] = t
    missing = sorted(stars - set(out))
    if missing: errs.append(f'★ questions with no script: {", ".join(missing[:8])} ({len(missing)})')
    if errs: sys.exit('\n'.join(errs))
    js = ('/* Generated by gen/likely_why.py from why/why.json: edit why.json and rerun. LIKELY_WHY[id] is the spoken\n'
          '   reasoning of a ★ question, read aloud by Hear why under its explanation. */\n'
          'const LIKELY_WHY = {\n' + ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}' for k, v in out.items()) + '\n};\n')
    open(os.path.join(SRC, 'likely_why.js'), 'w', encoding='utf-8').write(js)
    print(f'likely_why.js: {len(out)} scripts, {sum(len(v) for v in out.values())} characters')

if __name__ == '__main__':
    main()
