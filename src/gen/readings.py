#!/usr/bin/env python3
"""Textbook reading cards for the Guides tab.

Reads one card per chapter from src/readings/<id>.json (the fields are listed
in REQUIRED below) and writes src/readings.js, `const READINGS = [...]`, in the
order of META. META adds what the card files do not hold: the lecture date, the
module, and the guide sections a card's chips jump to. A chip is a module
heading prefix ("Module 7b"); the page shows it only when the Guides tab has a
heading that starts with it.

A META entry without a card file is skipped and reported, so a chapter that
could not be read is listed here without being invented.

    python3 gen/readings.py
"""
import glob, json, os, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # src/
CARDS = os.path.join(HERE, 'readings')
OUT = os.path.join(HERE, 'readings.js')

META = {
    'ch22': dict(module='7b', date='Mon 12 Oct',
                 guide=[['Module 7b', 'Guide: Module 7b, PK-PD']]),
    'ch18': dict(module='8', date='Wed 14 Oct',
                 guide=[['Module 8', 'Guide: Module 8, nonlinear PK']]),
}

REQUIRED = ['id', 'title', 'source', 'file', 'lecture', 'kind', 'about', 'sections',
            'lecture_use', 'read_for', 'beyond_lecture', 'terms', 'discussed_in_class',
            'her_words', 'truncated']


def main():
    cards = {}
    for f in sorted(glob.glob(os.path.join(CARDS, '*.json'))):
        c = json.load(open(f, encoding='utf-8'))
        missing = [k for k in REQUIRED if k not in c]
        if missing:
            sys.exit('%s: missing %s' % (os.path.basename(f), ', '.join(missing)))
        cards[c['id']] = c
    unknown = [k for k in cards if k not in META]
    if unknown:
        sys.exit('cards without META: ' + ', '.join(unknown))
    out = []
    for rid, m in META.items():
        if rid not in cards:
            print('readings.js: no card file for %s, skipped' % rid)
            continue
        c = dict(cards[rid])
        c.update(module=m['module'], date=m['date'], guide=m['guide'])
        out.append(c)
    js = ('/* Generated by gen/readings.py from readings/*.json. Do not edit. */\n'
          'const READINGS = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
    assert '`' not in js and '${' not in js and '</' not in js
    open(OUT, 'w', encoding='utf-8').write(js)
    print('readings.js: %d reading%s' % (len(out), '' if len(out) == 1 else 's'))


if __name__ == '__main__':
    main()
